// Smooth scroll
document.addEventListener("click", (e) => {
  const a = e.target.closest('a[href^="#"]');
  if (!a) return;
  const id = a.getAttribute("href");
  if (!id || id === "#") return;
  const target = document.querySelector(id);
  if (!target) return;
  e.preventDefault();
  target.scrollIntoView({ behavior: "smooth", block: "start" });
});

// ===== Auto infinite marquee (for #marquee inside #track) =====
(function () {
  const track = document.getElementById("track");
  const marquee = document.getElementById("marquee");
  if (!track || !marquee) {
    console.warn("Missing #track or #marquee");
    return;
  }

  const SPEED = 100; // px/sec
  let paused = false;
  let x = 0;
  let lastTs = 0;
  let raf = 0;
  let loopWidth = 0;

  function waitImages() {
    const imgs = Array.from(marquee.querySelectorAll("img"));
    return Promise.all(
      imgs.map((img) => {
        if (img.complete && img.naturalWidth > 0) return Promise.resolve();
        return new Promise((res) => {
          img.addEventListener("load", res, { once: true });
          img.addEventListener("error", res, { once: true });
        });
      }),
    );
  }

  function buildLoop() {
    Array.from(marquee.querySelectorAll("[data-clone='1']")).forEach((n) =>
      n.remove(),
    );

    const originals = Array.from(marquee.children).filter((el) =>
      el.classList?.contains("slide"),
    );
    if (!originals.length) return;

    const frag = document.createDocumentFragment();
    originals.forEach((s) => {
      const c = s.cloneNode(true);
      c.dataset.clone = "1";
      frag.appendChild(c);
    });
    marquee.appendChild(frag);

    loopWidth = marquee.scrollWidth / 2;

    x = 0;
    marquee.style.transform = `translate3d(${x}px,0,0)`;
  }

  function tick(ts) {
    if (!lastTs) lastTs = ts;
    const dt = Math.min(40, ts - lastTs);
    lastTs = ts;

    if (!paused && loopWidth > 0) {
      x -= (SPEED * dt) / 1000;
      if (-x >= loopWidth) x += loopWidth;
      marquee.style.transform = `translate3d(${x}px,0,0)`;
    }

    raf = requestAnimationFrame(tick);
  }

  function start() {
    cancelAnimationFrame(raf);
    lastTs = 0;
    raf = requestAnimationFrame(tick);
  }

  track.addEventListener("mouseenter", () => (paused = true));
  track.addEventListener("mouseleave", () => (paused = false));
  track.addEventListener("touchstart", () => (paused = true), {
    passive: true,
  });
  track.addEventListener(
    "touchend",
    () => setTimeout(() => (paused = false), 600),
    { passive: true },
  );

  (async () => {
    await waitImages();
    buildLoop();
    start();
  })();

  window.addEventListener("resize", () => buildLoop());
})();

